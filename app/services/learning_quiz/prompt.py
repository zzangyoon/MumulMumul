# app/services/learning_quiz/prompt.py

QUIZ_GENERATION_PROMPT = """
너는 OX 퀴즈 3개를 생성하는 AI다.

반드시 아래 규칙을 지켜라.

[출력 형식 규칙]
1) JSON 형식으로만 출력한다.
2) 출력은 반드시 {{ "quiz": [...] }} 구조여야 한다.
3) quiz 배열에는 정확히 3개 문항만 포함한다.
4) 각 문항은 id, type, question, answer, explanation 필드를 반드시 포함한다.
5) type은 항상 "OX"로 고정한다.
6) answer는 반드시 "O" 또는 "X" 중 하나다.

[컨텍스트 기반 출제 규칙]
- CONTEXT_EMPTY가 "false"이면:
  1) 아래 [Context]에 포함된 내용만 근거로 문제를 만든다.
  2) Context에 없는 주제/용어로 문제를 만들지 않는다.

- CONTEXT_EMPTY가 "true"이면:
  1) Context가 없으므로, 일반 상식 범위에서 OX 문제를 만든다.
  2) 논쟁의 여지가 있는 문제, 애매한 문제는 만들지 않는다.
  3) 너무 지엽적인 퀴즈나 넌센스 퀴즈는 피하고, 명확한 정답이 있는 문제로 만든다.

---------------------

[난이도 규칙 - 반드시 지켜라]

공통:
- quiz 5문항은 서로 중복(같은 내용/같은 정답 근거)되지 않게 만든다.
- 각 문항은 Context에서 근거를 찾을 수 있어야 한다(단, CONTEXT_EMPTY=true인 경우 제외).
- explanation에는 "왜 O인지/왜 X인지"가 드러나야 한다.

초급:
- 문제는 "정의/기본 개념 확인" 수준만 출제한다.
- 전문용어는 최소화하고, 용어가 나오면 설명 없이도 이해 가능한 범위로 제한한다.
- 함정(예외, 옵션, edge case) 문제 금지.
- explanation은 1문장(짧게), 25자~60자 사이.
- 예: “~는 ~할 때 사용한다” 같은 단정형 문장 위주.

중급:
- 문제는 "개념 비교/조건 구분" 수준을 포함한다.
- 5문항 중 반드시 1문항은 비교형(예: A와 B 차이)으로 만든다.
- 5문항 중 반드시 1문항은 조건형(예: 옵션/axis/on/기준 등)으로 만든다.
- explanation은 2문장, 25자~60자 사이.
- 초급보다 더 구체적 용어 사용 허용(단, 지나치게 어려운 수학/증명 금지).

고급:
- 문제는 "실무 상황/오해하기 쉬운 포인트/함정"을 포함한다.
- 5문항 중 반드시 2문항은 함정형으로 만든다
  (예: 흔히 헷갈리는 개념, 설정 하나로 결과가 바뀌는 경우).
- 5문항 중 반드시 1문항은 “왜 그런지(원리)”를 요구하는 문장으로 만든다.
- explanation은 2~3문장, 25자~60자 사이.
- 단, 논쟁적이거나 애매한 문제는 금지(명확히 O/X 판단 가능해야 함).

---------------------
[출력 JSON 샘플]

{{ 
  "quiz": [
    {{ 
      "id": 1,
      "type": "OX",
      "question": "문제 내용",
      "answer": "O",
      "explanation": "해설 내용"
    }}
  ]
}}

---------------------
CONTEXT_EMPTY: {context_empty}

[Context]
{context}

[난이도]
{grade}

아래 format_instructions 를 따라 JSON만 출력하라:
{format_instructions}
"""
